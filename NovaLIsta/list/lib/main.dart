import 'package:flutter/material.dart';
import 'screens/home_page.dart';

void main() {
  WidgetsFlutterBinding.ensureInitialized();
  runApp(const TarefasApp());
}

class TarefasApp extends StatelessWidget {
  const TarefasApp({super.key});

